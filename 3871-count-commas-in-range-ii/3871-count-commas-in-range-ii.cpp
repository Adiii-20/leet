class Solution {
public:
    long long countCommas(long long n) {
       if(n<1000) return 0;
       if(n>999 && n<1000000) return n-999;
       if(n>999999 && n<1000000000) return 2*(n-999999)+1000000-1000;
       if(n>999999999 && n<1000000000000) return 3*(n-999999999)+2*(1000000000-1000000)+1000000-1000;
       if(n<1000000000000000) return 4*(n-999999999999)+3*(1000000000000-1000000000)+2*(1000000000-1000000)+1000000-1000;
       return 5+4*(1000000000000000-1000000000000)+3*(1000000000000-1000000000)+2*(1000000000-1000000)+1000000-1000;
    }
};